-- 6. БИЛЕТЫ (tickets) — ~30% мест на каждый сеанс
INSERT INTO tickets (watching_id, seat_id, price, booked_at, status, is_active)
SELECT
    w.id,
    s.id,
    ROUND(
        (CASE
            WHEN s.row_number <= 3 THEN 280 + (s.row_number * 15)
            WHEN s.row_number <= 6 THEN 380 + (s.row_number * 20)
            WHEN s.row_number <= 10 THEN 480 + (s.row_number * 25)
            ELSE 600 + (s.row_number * 30)
        END + (s.seat_number % 5) * 10)::numeric, 2
    ),
    CASE
        WHEN (w.id * 7 + s.id * 3) % 10 < 8 THEN
            w.start_time - (((w.id * 13 + s.id * 7) % 72 + 24) || ' hours')::interval
        ELSE NULL
    END,
    CASE
        WHEN (w.id * 11 + s.id * 5) % 10 < 6 THEN 'paid'::ticket_status
        WHEN (w.id * 11 + s.id * 5) % 10 < 8 THEN 'booked'::ticket_status
        ELSE 'available'::ticket_status
    END,
    true
FROM watchings w
JOIN seats s ON s.theater_id = w.theater_id
WHERE s.seat_number % 3 = 1;
